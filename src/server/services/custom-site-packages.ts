import AdmZip from "adm-zip";
import { createHash } from "node:crypto";
import { access, mkdir, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, normalize, relative, sep } from "node:path";
import { getCustomSitePublicBasePath, getCustomSitesBaseDir } from "@/server/services/custom-site-paths";

const MAX_EXTRACTED_FILES = 2000;
const MAX_EXTRACTED_BYTES = 150 * 1024 * 1024;

export type CustomSitePackageSource = "zip" | "github" | "generic";

export type CustomStaticSiteManifest = {
  siteId: string;
  entryPath: string;
  sourceType: CustomSitePackageSource;
  repositoryUrl?: string | null;
  packageFileName?: string | null;
  packageSha256?: string | null;
  fileCount: number;
  totalBytes: number;
  importedAt: string;
  publicBasePath: string;
};

export type ParsedGithubRepositoryUrl = {
  owner: string;
  repo: string;
  ref?: string;
};

export function parseGithubRepositoryUrl(value: string): ParsedGithubRepositoryUrl | null {
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    return null;
  }

  if (url.hostname !== "github.com" && url.hostname !== "www.github.com") {
    return null;
  }

  const parts = url.pathname.split("/").filter(Boolean);
  if (parts.length < 2) return null;

  const [owner, repoWithSuffix] = parts;
  const repo = repoWithSuffix.replace(/\.git$/i, "");
  const treeIndex = parts.indexOf("tree");
  const ref = treeIndex >= 0 ? parts.slice(treeIndex + 1).join("/") : undefined;

  if (!owner || !repo) return null;
  return { owner, repo, ref: ref || undefined };
}

export async function downloadGithubRepositoryZip(repositoryUrl: string) {
  const parsed = parseGithubRepositoryUrl(repositoryUrl);
  if (!parsed) {
    throw new Error("CUSTOM_SITE_GITHUB_URL_INVALID");
  }

  const repositoryResponse = await fetch(
    `https://api.github.com/repos/${encodeURIComponent(parsed.owner)}/${encodeURIComponent(parsed.repo)}`,
    {
      headers: {
        Accept: "application/vnd.github+json",
        "User-Agent": "Vase-Custom-Site-Importer",
      },
      cache: "no-store",
    },
  );

  if (!repositoryResponse.ok) {
    throw new Error("CUSTOM_SITE_GITHUB_REPOSITORY_NOT_FOUND");
  }

  const repository = (await repositoryResponse.json()) as { default_branch?: string };
  const ref = parsed.ref || repository.default_branch || "main";
  const encodedRef = ref.split("/").map(encodeURIComponent).join("/");
  const zipUrl = `https://codeload.github.com/${encodeURIComponent(parsed.owner)}/${encodeURIComponent(parsed.repo)}/zip/refs/heads/${encodedRef}`;
  const zipResponse = await fetch(zipUrl, {
    headers: { "User-Agent": "Vase-Custom-Site-Importer" },
    cache: "no-store",
  });

  if (!zipResponse.ok) {
    throw new Error("CUSTOM_SITE_GITHUB_DOWNLOAD_FAILED");
  }

  const buffer = new Uint8Array(await zipResponse.arrayBuffer());
  return {
    bytes: buffer,
    fileName: `${parsed.owner}-${parsed.repo}-${ref.replace(/[^a-zA-Z0-9._-]+/g, "-")}.zip`,
    ref,
  };
}

function isSafeRelativePath(path: string) {
  if (!path || path.startsWith("/") || path.startsWith("\\") || /^[a-zA-Z]:/.test(path)) {
    return false;
  }
  const normalized = normalize(path).replaceAll("\\", "/");
  return !normalized.split("/").some((part) => part === "..");
}

function normalizeZipEntryName(entryName: string) {
  return entryName.replaceAll("\\", "/");
}

function toOutputPath(entryName: string, rootPrefix: string) {
  const normalizedEntryName = normalizeZipEntryName(entryName);
  const withoutRoot = rootPrefix && normalizedEntryName.startsWith(rootPrefix)
    ? normalizedEntryName.slice(rootPrefix.length)
    : normalizedEntryName;
  return withoutRoot.replace(/^\/+/, "");
}

const preferredBuildOutputDirs = new Set(["dist", "build", "out", "public", "public_html"]);

function getIndexCandidateScore(entryName: string) {
  const parts = normalizeZipEntryName(entryName).toLowerCase().split("/").filter(Boolean);
  const parentDir = parts.at(-2);

  if (parentDir && preferredBuildOutputDirs.has(parentDir)) {
    return 0;
  }
  if (parts.length === 1) {
    return 1;
  }
  return 2 + parts.length;
}

function findIndexEntry(entries: AdmZip.IZipEntry[]) {
  const candidates = entries
    .filter((entry) => {
      const name = normalizeZipEntryName(entry.entryName).toLowerCase();
      return !entry.isDirectory && (name.endsWith("/index.html") || name === "index.html");
    })
    .sort((a, b) => getIndexCandidateScore(a.entryName) - getIndexCandidateScore(b.entryName));
  return candidates[0] ?? null;
}

function assertInsideBase(baseDir: string, targetPath: string) {
  const rel = relative(baseDir, targetPath);
  if (rel.startsWith("..") || rel === ".." || rel.includes(`..${sep}`)) {
    throw new Error("CUSTOM_SITE_PATH_INVALID");
  }
}

export async function extractCustomSitePackage(input: {
  siteId: string;
  zipBytes: Uint8Array;
  baseDir?: string;
}) {
  const baseDir = input.baseDir ?? getCustomSitesBaseDir();
  const zip = new AdmZip(Buffer.from(input.zipBytes));
  const entries = zip.getEntries();
  const indexEntry = findIndexEntry(entries);
  if (!indexEntry) {
    throw new Error("CUSTOM_SITE_INDEX_MISSING");
  }

  const rootPrefix = normalizeZipEntryName(indexEntry.entryName).slice(0, -("index.html".length));
  const siteRoot = join(baseDir, input.siteId);
  const tempDir = join(siteRoot, `next-${Date.now()}`);
  const currentDir = join(siteRoot, "current");
  const previousDir = join(siteRoot, "previous");
  let fileCount = 0;
  let totalBytes = 0;

  assertInsideBase(baseDir, siteRoot);
  await mkdir(tempDir, { recursive: true });

  try {
    for (const entry of entries) {
      if (entry.isDirectory) continue;
      const entryName = normalizeZipEntryName(entry.entryName);
      if (entryName.includes("__MACOSX/")) continue;
      if (rootPrefix && !entryName.startsWith(rootPrefix)) continue;

      const outputPath = toOutputPath(entryName, rootPrefix);
      if (!isSafeRelativePath(outputPath)) {
        throw new Error("CUSTOM_SITE_PATH_INVALID");
      }

      const targetPath = join(tempDir, outputPath);
      assertInsideBase(tempDir, targetPath);

      const data = entry.getData();
      totalBytes += data.byteLength;
      fileCount += 1;

      if (fileCount > MAX_EXTRACTED_FILES) {
        throw new Error("CUSTOM_SITE_FILE_LIMIT_EXCEEDED");
      }
      if (totalBytes > MAX_EXTRACTED_BYTES) {
        throw new Error("CUSTOM_SITE_SIZE_LIMIT_EXCEEDED");
      }

      await mkdir(dirname(targetPath), { recursive: true });
      await writeFile(targetPath, data);
    }

    try {
      await access(currentDir);
      await rm(previousDir, { force: true, recursive: true });
      await rename(currentDir, previousDir);
    } catch {
      // nothing to backup
    }
    await rename(tempDir, currentDir);
  } catch (error) {
    await rm(tempDir, { force: true, recursive: true });
    throw error;
  }

  return {
    entryPath: "index.html",
    fileCount,
    totalBytes,
    storagePath: `custom-sites/${input.siteId}/current`,
  };
}

export async function rollbackCustomSitePackage(input: {
  siteId: string;
  baseDir?: string;
}) {
  const baseDir = input.baseDir ?? getCustomSitesBaseDir();
  const siteRoot = join(baseDir, input.siteId);
  const currentDir = join(siteRoot, "current");
  const previousDir = join(siteRoot, "previous");
  const rollbackTempDir = join(siteRoot, `rollback-${Date.now()}`);

  assertInsideBase(baseDir, siteRoot);
  assertInsideBase(siteRoot, currentDir);
  assertInsideBase(siteRoot, previousDir);

  await access(previousDir).catch(() => {
    throw new Error("CUSTOM_SITE_PREVIOUS_VERSION_MISSING");
  });

  await rm(rollbackTempDir, { force: true, recursive: true });
  await mkdir(siteRoot, { recursive: true });

  try {
    await access(currentDir);
    await rename(currentDir, rollbackTempDir);
  } catch {
    // no current version
  }

  await rename(previousDir, currentDir);

  if (rollbackTempDir) {
    try {
      await rm(previousDir, { force: true, recursive: true });
      await rename(rollbackTempDir, previousDir);
    } catch {
      await rm(rollbackTempDir, { force: true, recursive: true });
    }
  }

  return {
    entryPath: "index.html",
    storagePath: `custom-sites/${input.siteId}/current`,
    publicBasePath: getCustomSitePublicBasePath(input.siteId),
  };
}

export function createCustomStaticSiteManifest(input: {
  siteId: string;
  sourceType: CustomSitePackageSource;
  repositoryUrl?: string | null;
  packageFileName?: string | null;
  zipBytes?: Uint8Array | null;
  fileCount: number;
  totalBytes: number;
}): CustomStaticSiteManifest {
  const packageSha256 = input.zipBytes
    ? createHash("sha256").update(Buffer.from(input.zipBytes)).digest("hex")
    : null;

  return {
    siteId: input.siteId,
    entryPath: "index.html",
    sourceType: input.sourceType,
    repositoryUrl: input.repositoryUrl ?? null,
    packageFileName: input.packageFileName ?? null,
    packageSha256,
    fileCount: input.fileCount,
    totalBytes: input.totalBytes,
    importedAt: new Date().toISOString(),
    publicBasePath: getCustomSitePublicBasePath(input.siteId),
  };
}
