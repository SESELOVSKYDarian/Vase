import AdmZip from "adm-zip";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { describe, expect, test } from "vitest";
import {
  extractCustomSitePackage,
  parseGithubRepositoryUrl,
} from "@/server/services/custom-site-packages";

function buildZip(entries: Record<string, string>) {
  const zip = new AdmZip();
  for (const [path, content] of Object.entries(entries)) {
    zip.addFile(path, Buffer.from(content));
  }
  return new Uint8Array(zip.toBuffer());
}

describe("custom site packages", () => {
  test("extracts a GitHub-style zip root into a public site directory", async () => {
    const baseDir = await mkdtemp(join(tmpdir(), "vase-custom-site-"));
    try {
      const result = await extractCustomSitePackage({
        siteId: "site_123",
        zipBytes: buildZip({
          "piquim-main/index.html": '<html><head></head><body><script src="/assets/app.js"></script></body></html>',
          "piquim-main/assets/app.js": "console.log('ok')",
        }),
        baseDir,
      });

      expect(result.entryPath).toBe("index.html");
      expect(result.fileCount).toBe(2);
      expect(await readFile(join(baseDir, "site_123", "current", "index.html"), "utf8"))
        .toContain("/assets/app.js");
      expect(await readFile(join(baseDir, "site_123", "current", "assets", "app.js"), "utf8"))
        .toContain("ok");
    } finally {
      await rm(baseDir, { force: true, recursive: true });
    }
  });

  test("rejects packages without index.html", async () => {
    const baseDir = await mkdtemp(join(tmpdir(), "vase-custom-site-"));
    try {
      await expect(
        extractCustomSitePackage({
          siteId: "site_123",
          zipBytes: buildZip({
            "dist/assets/app.js": "console.log('missing index')",
          }),
          baseDir,
        }),
      ).rejects.toThrow("CUSTOM_SITE_INDEX_MISSING");
    } finally {
      await rm(baseDir, { force: true, recursive: true });
    }
  });

  test("prefers compiled output over a source index.html", async () => {
    const baseDir = await mkdtemp(join(tmpdir(), "vase-custom-site-"));
    try {
      await extractCustomSitePackage({
        siteId: "site_123",
        zipBytes: buildZip({
          "piquim-main/web/index.html": '<html><body><script type="module" src="/src/main.tsx"></script></body></html>',
          "piquim-main/web/src/main.tsx": "console.log('source')",
          "piquim-main/web/dist/index.html": '<html><body><script src="/assets/app.js"></script></body></html>',
          "piquim-main/web/dist/assets/app.js": "console.log('compiled')",
        }),
        baseDir,
      });

      expect(await readFile(join(baseDir, "site_123", "current", "index.html"), "utf8"))
        .toContain("/assets/app.js");
      expect(await readFile(join(baseDir, "site_123", "current", "assets", "app.js"), "utf8"))
        .toContain("compiled");
    } finally {
      await rm(baseDir, { force: true, recursive: true });
    }
  });

  test("normalizes Windows-style zip paths before extracting assets", async () => {
    const baseDir = await mkdtemp(join(tmpdir(), "vase-custom-site-"));
    try {
      await extractCustomSitePackage({
        siteId: "site_123",
        zipBytes: buildZip({
          "dist\\index.html": '<html><body><script src="/assets/app.js"></script></body></html>',
          "dist\\assets\\app.js": "console.log('windows paths')",
        }),
        baseDir,
      });

      expect(await readFile(join(baseDir, "site_123", "current", "assets", "app.js"), "utf8"))
        .toContain("windows paths");
    } finally {
      await rm(baseDir, { force: true, recursive: true });
    }
  });

  test("parses GitHub repository URLs with an optional branch", () => {
    expect(parseGithubRepositoryUrl("https://github.com/VASE-Company/piquim/tree/main")).toEqual({
      owner: "VASE-Company",
      repo: "piquim",
      ref: "main",
    });
  });
});
